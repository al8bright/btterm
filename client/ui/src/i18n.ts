export type MessageKey = keyof typeof ko;

/** 사전에 있는 키인가 */
export function hasMessage(key: string): key is MessageKey {
  return Object.hasOwn(ko, key);
}

/**
 * 오류 코드를 문구 키로(결정 UX6). 사전에 없는 코드는 코드 대신 fallback 문구를 쓴다.
 * 예: messageFor('error', 'dns', 'error.open-failed') → 'error.dns'
 */
export function messageFor(prefix: string, code: string, fallback: MessageKey): MessageKey {
  const key = `${prefix}.${code}`;
  return hasMessage(key) ? key : fallback;
}

/** 메시지를 찾고 {이름} 자리를 값으로 바꾼다. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const text: string = ko[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
